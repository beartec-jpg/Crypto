// Compliance framing for every AI prompt (technical scenarios, not advice).
//
// BEARTEC LTD is not authorised by the FCA. AI output must be general, educational
// technical analysis: no buy/sell calls, no personal recommendations, no
// instructions to enter, stop out or take profit, and nothing that invites or
// induces anyone to buy a cryptoasset (FSMA 2000 s21). See the Regulatory Note
// (data room) and keep this file in sync with api/_lib/scenarioFraming.ts.
//
// Note: JSON field names such as `entry`, `stopLoss` and `targets` are kept for
// backwards compatibility with stored data and the UI. Their MEANING is defined
// below as neutral scenario levels; the UI labels them accordingly.

export const SCENARIO_FRAMING_PROMPT =
  'COMPLIANCE RULES (override anything else in these instructions): ' +
  'You are an automated software tool producing general, educational technical analysis of public market data. ' +
  'You are not a person, adviser or broker, and you do not know the reader or their circumstances. ' +
  'Describe conditional technical scenarios only (for example: "if price closes above X, the bearish structure would be invalidated; ' +
  'the next reference level on the chart is Y"). ' +
  'Never tell anyone to buy, sell, hold, enter, exit, go long, go short, open or close a position, set a stop-loss or take profit. ' +
  'Never use imperative trading language, "trade alert", "signal", "setup to take", "entry", "take profit" or "stop-loss" in prose. ' +
  'Never mention or suggest leverage, margin, perpetual futures, derivatives positions or position sizing. ' +
  'Never tailor output to a user\'s funds, holdings or goals, and never claim or imply profit, returns or certainty. ' +
  'Where a JSON schema asks for fields named entry, entryZone, stopLoss, targets, tp1Rationale, tp2Rationale or riskRewardRatio, ' +
  'treat them as neutral chart levels: entry/entryZone = the scenario trigger level or zone (where the scenario would become active), ' +
  'stopLoss = the invalidation level (where the scenario would no longer hold), targets = reference levels the scenario points towards, ' +
  'and riskRewardRatio = an illustrative distance ratio only. Write any rationale text in neutral, descriptive, conditional language. ' +
  'direction LONG means a bullish scenario and SHORT means a bearish scenario; describe them that way in prose.';

/** Prepend the compliance framing to a system prompt. Idempotent. */
export function withScenarioFraming(systemPrompt: string): string {
  if (systemPrompt.startsWith('COMPLIANCE RULES')) return systemPrompt;
  return `${SCENARIO_FRAMING_PROMPT}\n\n${systemPrompt}`;
}

export const SCENARIO_DISCLAIMER_TEXT =
  'Educational technical scenarios generated by automated software. Not financial advice and not a recommendation to buy, sell or hold any cryptoasset. ' +
  'BEARTEC LTD is not authorised by the FCA. Cryptoassets are high risk and you can lose all the money you put in.';

/** Ensure a chat message list starts with the compliance framing (adds a system message if none). */
export function withScenarioFramingMessages<T extends { role: string; content: any }>(messages: T[]): T[] {
  const hasSystem = messages.some((m) => m.role === 'system');
  if (!hasSystem) {
    return [{ role: 'system', content: SCENARIO_FRAMING_PROMPT } as T, ...messages];
  }
  return messages.map((m) =>
    m.role === 'system' && typeof m.content === 'string'
      ? ({ ...m, content: withScenarioFraming(m.content) } as T)
      : m,
  );
}
